namespace Commando.Licensing;

public static class LicenseSecrets
{
    public static byte[] PublicKeyData => Unfolded();

    static byte[] Unfolded()
    {
        var mask = new byte[]
        {
            0x5A, 0x3C, 0x91, 0xE7, 0x2B, 0x44, 0xD8, 0x0F,
            0x66, 0xA1, 0x7C, 0x19, 0xB3, 0x58, 0xC2, 0x04,
        };
        var packed = new byte[]
        {
            0x5E, 0x97, 0x4A, 0x1D, 0x00, 0x1B, 0xE3, 0xC6,
            0x28, 0x90, 0xE1, 0xFA, 0x25, 0x99, 0x1D, 0x1B,
            0xBC, 0x8D, 0xAC, 0xD2, 0x3D, 0x9F, 0xDB, 0xE1,
            0x26, 0x67, 0xC4, 0xD3, 0x0D, 0xE5, 0xCA, 0x7F,
        };
        var plain = new byte[packed.Length];
        for (var index = 0; index < packed.Length; index++)
        {
            plain[index] = (byte)(packed[index] ^ mask[index % mask.Length]);
        }

        return plain;
    }
}
