import Foundation

enum LicenseEndpoints {
    static var checkURL: URL {
        URL(string: decode(packedCheck))!
    }

    static var reportURL: URL {
        URL(string: decode(packedReport))!
    }

    private static let mask: [UInt8] = [0x5A, 0x3C, 0x91, 0xE7, 0x2B, 0x44, 0xD8, 0x0F, 0x66, 0xA1, 0x7C, 0x19, 0xB3, 0x58, 0xC2, 0x04]

    private static let packedCheck: [UInt8] = [
        0x32, 0x48, 0xE5, 0x97, 0x58, 0x7E, 0xF7, 0x20, 0x16, 0xD3, 0x13, 0x61, 0xCA, 0x76, 0xAF, 0x65,
        0x34, 0x48, 0xF8, 0x84, 0x44, 0x36, 0xBD, 0x21, 0x08, 0xDB, 0x53, 0x75, 0xD6, 0x3F, 0xA3, 0x67,
        0x23, 0x5D, 0xF8, 0xC8, 0x48, 0x2B, 0xB5, 0x62, 0x07, 0xCF, 0x18, 0x76, 0x9C, 0x34, 0xAB, 0x67,
        0x3F, 0x52, 0xE2, 0x82,
    ]

    private static let packedReport: [UInt8] = [
        0x32, 0x48, 0xE5, 0x97, 0x58, 0x7E, 0xF7, 0x20, 0x16, 0xD3, 0x13, 0x61, 0xCA, 0x76, 0xAF, 0x65,
        0x34, 0x48, 0xF8, 0x84, 0x44, 0x36, 0xBD, 0x21, 0x08, 0xDB, 0x53, 0x75, 0xD6, 0x3F, 0xA3, 0x67,
        0x23, 0x5D, 0xF8, 0xC8, 0x48, 0x2B, 0xB5, 0x62, 0x07, 0xCF, 0x18, 0x76, 0x9C, 0x2A, 0xA7, 0x74,
        0x35, 0x4E, 0xE5,
    ]

    private static func decode(_ packed: [UInt8]) -> String {
        let plain = packed.enumerated().map { index, byte in
            byte ^ mask[index % mask.count]
        }

        return String(bytes: plain, encoding: .utf8) ?? ""
    }
}
